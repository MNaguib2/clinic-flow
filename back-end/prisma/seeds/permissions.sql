INSERT INTO `permissions` (`page_id`, `code`, `name_en`, `name_ar`, `description_en`, `description_ar`)
SELECT page.`id`, permission.`code`,
    LEFT(permission.`description_en`, 150),
    LEFT(permission.`description_ar`, 150),
    permission.`description_en`, permission.`description_ar`
FROM `permission_seed` AS permission
JOIN `permission_pages` AS page
    ON page.`key` = SUBSTRING_INDEX(permission.`code`, '.', 1)
ON DUPLICATE KEY UPDATE
    `page_id` = VALUES(`page_id`),
    `name_en` = VALUES(`name_en`),
    `name_ar` = VALUES(`name_ar`),
    `description_en` = VALUES(`description_en`),
    `description_ar` = VALUES(`description_ar`);

